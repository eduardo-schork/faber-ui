import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

import { createTokenCSSVariables } from '@faber-ui/tokens';

import { DARK_THEME } from '../src/theme/dark-theme.ts';
import { LIGHT_THEME } from '../src/theme/light-theme.ts';
import { THEME_MODES } from '../src/theme/theme.constants.ts';
import { createThemeCSSVariables } from '../src/theme-variables/theme-variables.ts';

const outputPath = fileURLToPath(new URL('../src/theme-variables/styles.css', import.meta.url));

function createVariableDeclarations(theme, indentation = '  ') {
  return Object.entries(createThemeCSSVariables(theme))
    .map(([name, value]) => `${indentation}${name}: ${value};`)
    .join('\n');
}

function createTokenDeclarations() {
  return Object.entries(createTokenCSSVariables())
    .map(([name, value]) => `  ${name}: ${value};`)
    .join('\n');
}

function createThemeStyles() {
  const tokenVariables = createTokenDeclarations();
  const lightVariables = createVariableDeclarations(LIGHT_THEME);
  const darkVariables = createVariableDeclarations(DARK_THEME);
  const nestedDarkVariables = createVariableDeclarations(DARK_THEME, '    ');

  return `/* This file is generated by scripts/generate-theme-styles.mjs. Do not edit manually. */
:root {
${tokenVariables}
}

:root,
[data-theme='${THEME_MODES.LIGHT}'],
[data-theme='${THEME_MODES.SYSTEM}'] {
  color-scheme: light;
${lightVariables}
}

[data-theme='${THEME_MODES.DARK}'] {
  color-scheme: dark;
${darkVariables}
}

@media (prefers-color-scheme: dark) {
  [data-theme='${THEME_MODES.SYSTEM}'] {
    color-scheme: dark;
${nestedDarkVariables}
  }
}
`;
}

const expectedStyles = createThemeStyles();
const checkOnly = process.argv.includes('--check');

if (checkOnly) {
  const currentStyles = await readFile(outputPath, 'utf8');

  if (currentStyles !== expectedStyles) {
    throw new Error('Theme CSS is out of date. Run `bun run generate:styles` in packages/themes.');
  }
} else {
  await writeFile(outputPath, expectedStyles);
}
